"""Create a separate CAD result and verify it against the original live export."""
from __future__ import annotations

import hashlib
import json
import math
import os
import re
import sys
from pathlib import Path

from .barriers import LAYER, CATEGORY_LAYER, category_label

_vendor = str(Path(__file__).resolve().parents[1] / "runtime_vendor")
if _vendor not in sys.path:
    sys.path.insert(0, _vendor)


def library():
    cache = Path(__file__).resolve().parents[1] / "data" / "cad_cache"
    cache.mkdir(parents=True, exist_ok=True)
    os.environ.setdefault("XDG_CACHE_HOME", str(cache))
    import ezdxf
    ezdxf.options.preserve_proxy_graphics(True)
    return ezdxf


def point(value):
    if not isinstance(value, (list, tuple)) or len(value) not in (2, 3):
        raise ValueError("Координата должна содержать X, Y и необязательный Z")
    values = tuple(float(v) for v in value)
    if not all(math.isfinite(v) for v in values):
        raise ValueError("Координаты должны быть конечными")
    if len(values) == 3 and abs(values[2]) > 0.001:
        raise ValueError("Исполнитель плоских схем ПП принимает только Z=0")
    return values[:2]


def normalized(value):
    if isinstance(value, float):
        return round(value, 6)
    if isinstance(value, dict):
        return {k: normalized(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)) or value.__class__.__name__ in {"Vec2", "Vec3"}:
        return [normalized(x) for x in value]
    return value


def equivalent(a, b):
    """Allow only CAD floating-point serialization noise, never rounded millimetres."""
    if isinstance(a, dict) and isinstance(b, dict):
        return a.keys()==b.keys() and all(equivalent(v,b[k]) for k,v in a.items())
    if isinstance(a, (list,tuple)) and isinstance(b, (list,tuple)):
        return len(a)==len(b) and all(equivalent(x,y) for x,y in zip(a,b))
    if isinstance(a,float) and isinstance(b,(int,float)) or isinstance(b,float) and isinstance(a,(int,float)):
        return math.isclose(a,b,rel_tol=0,abs_tol=0.00001)
    return a==b


def signature(entity):
    attrs = entity.dxf.all_existing_dxf_attribs()
    attrs.pop("handle", None)
    attrs.pop("owner", None)
    kind = entity.dxftype()
    if kind == "VIEWPORT":
        if "visual_style_handle" in attrs:
            attrs["visualstyle_handle"] = attrs.pop("visual_style_handle")
        # AutoCAD serializes these ambient-light defaults explicitly on SaveAs.
        attrs.setdefault("ambient_light_color_1", 250)
        attrs.setdefault("ambient_light_color_2", 3355443)
    if kind == "MTEXT":
        for key in ("defined_height", "width"):
            if not attrs.get(key):
                attrs.pop(key, None)
        if attrs.get("flow_direction") == 5 and entity.doc:
            style = entity.doc.styles.get(entity.dxf.style)
            if not style.dxf.flags & 4:
                attrs["flow_direction"] = 1
    if kind == "DIMENSION":
        # Cached measurements are regenerated by AutoCAD. Definition points,
        # text overrides and the displayed block remain independently checked.
        attrs.pop("actual_measurement", None)
        attrs.pop("geometry", None)
        for key in ("unknown1", "flip_arrow_1", "flip_arrow_2"):
            if attrs.get(key) == 0:
                attrs.pop(key, None)
    if kind == "DIMSTYLE" and not attrs.get("dimtxsty"):
        attrs["dimtxsty"] = "Standard"
    if kind == "LAYER" and attrs.get("unknown1") == "0":
        attrs.pop("unknown1")
    # DXF and AutoCAD may omit explicit default values on serialization.
    # Compare effective values: removing a true default retains every override.
    for key, value in list(attrs.items()):
        if normalized(value) == normalized(entity.dxf.dxf_default_value(key)):
            attrs.pop(key)
    result = {"type": entity.dxftype(), "attributes": normalized(attrs)}
    if kind == "DIMENSION" and entity.doc and entity.dxf.get("geometry"):
        block = entity.doc.blocks.get(entity.dxf.geometry)
        result["display_block"] = {"base_point":normalized(block.block.dxf.base_point),
                                   "entities":[signature(e) for e in block]}
    if entity.dxftype() == "LWPOLYLINE":
        result["vertices"] = normalized(list(entity.get_points()))
    elif entity.dxftype() == "MTEXT":
        result["text"] = entity.text
    elif entity.dxftype() == "POLYLINE":
        result["vertices"] = [signature(v) for v in entity.vertices]
    elif entity.dxftype() == "INSERT":
        result["attribs"] = [signature(a) for a in entity.attribs]
    if entity.xdata:
        result["xdata"] = {k: normalized([(t.code, t.value) for t in v]) for k,v in entity.xdata.data.items()}
    if kind in {"HATCH", "MPOLYGON"}:
        from ezdxf.lldxf.tagwriter import TagCollector
        collector = TagCollector(dxfversion=entity.doc.dxfversion)
        entity.paths.export_dxf(collector, kind)
        result["boundary_paths"] = normalized([(t.code,t.value) for t in collector.tags])
    if kind == "SPLINE":
        for name in ("control_points", "fit_points", "knots", "weights"):
            result[name] = normalized(getattr(entity,name).tolist())
    return result


def model_snapshot(doc):
    return {e.dxf.handle: signature(e) for e in doc.modelspace()}


def supporting_snapshot(doc):
    """Protect blocks, paper layouts and shared formatting as well as modelspace."""
    # Anonymous dimension blocks are checked by their owning dimensions,
    # because AutoCAD can renumber them when saving a complex source drawing.
    return {"blocks":{b.name:{"base_point":normalized(b.block.dxf.base_point),
                             "entities":[signature(e) for e in b]} for b in doc.blocks
                      if not b.name.lower().startswith("*model_space") and not re.fullmatch(r"\*D\d+",b.name,re.I)},
            "styles":{s.dxf.name:signature(s) for s in doc.styles},
            "dimstyles":{s.dxf.name:signature(s) for s in doc.dimstyles},
            "layers":{s.dxf.name:signature(s) for s in doc.layers}}


def supporting_changes(before, doc):
    after = supporting_snapshot(doc)
    return [f"{group}: {name}" for group, entries in before.items() for name,value in entries.items()
            if not equivalent(after.get(group, {}).get(name),value)]


def protected_changes(before, doc):
    after = model_snapshot(doc)
    missing = sorted(set(before) - set(after))
    changed = sorted(h for h in before.keys() & after.keys() if not equivalent(before[h],after[h]))
    return {"missing": missing, "changed": changed}


def text_style(doc, profile, prefix):
    font = profile.get("font_file", "isocpeur.ttf")
    width = profile.get("width_factor", profile.get("style_width_factor", 1.0))
    oblique = profile.get("oblique_angle", profile.get("style_oblique_angle_degrees", 0.0))
    attrs = {"font": font, "width": width, "oblique": oblique, "height": 0}
    digest = hashlib.sha256(json.dumps(attrs, sort_keys=True).encode()).hexdigest()[:8]
    name = "ПП_" + prefix + "_" + digest
    if name not in doc.styles:
        style = doc.styles.new(name, dxfattribs=attrs)
        families = {"isocpeur.ttf":"ISOCPEUR", "tahoma.ttf":"Tahoma"}
        if font.casefold() in families:
            style.set_xdata("ACAD", [(1000,families[font.casefold()]),(1071,34)])
    else:
        existing = doc.styles.get(name)
        if any(normalized(existing.dxf.get_default(k)) != normalized(v) for k,v in attrs.items()):
            raise ValueError("Стиль ПП с таким именем уже изменён: " + name)
    return name


def dimensions_style(doc, profile):
    data = profile["dimensions"]
    if data.get("arrow_block") == "_None" and "_None" not in doc.blocks:
        doc.blocks.new("_None")
    name = "ПП_Размеры_" + hashlib.sha256(json.dumps(data["variables"], sort_keys=True).encode()).hexdigest()[:8]
    if name not in doc.dimstyles:
        attrs = dict(data["variables"])
        attrs["dimtxsty"] = text_style(doc, data, "Размеры")
        doc.dimstyles.new(name, dxfattribs=attrs)
    else:
        existing = doc.dimstyles.get(name)
        for key,value in data["variables"].items():
            if key != "dimtxsty" and normalized(existing.dxf.get_default(key)) != normalized(value):
                raise ValueError("Размерный стиль ПП изменён: " + name)
    return name


def add_mtext(model, text, position, style, profile, color=1):
    return model.add_mtext(text, dxfattribs={"insert": point(position), "layer": LAYER,
        "style": style, "char_height": profile["text_height"], "width": profile["width"],
        "attachment_point": 1, "line_spacing_factor": profile.get("line_spacing", profile.get("line_spacing_factor", 1)),
        "line_spacing_style": 1, "color": color, "lineweight": 0})


def build_dxf(source, destination, plan, profile):
    ezdxf = library()
    doc = ezdxf.readfile(source)
    if doc.units != 4:
        raise ValueError("Экспортированный чертёж должен быть в миллиметрах")
    if profile.get("category", {}).get("layer") != CATEGORY_LAYER:
        raise ValueError(f"Профиль категорий должен требовать слой {CATEGORY_LAYER}")
    before = model_snapshot(doc)
    supporting_before = supporting_snapshot(doc)
    if LAYER not in doc.layers:
        doc.layers.new(LAYER, dxfattribs={"color": 1, "lineweight": 50})
    if CATEGORY_LAYER not in doc.layers:
        doc.layers.new(CATEGORY_LAYER, dxfattribs={"color": 1, "lineweight": 0})
    layer = doc.layers.get(LAYER)
    if layer.is_off() or layer.is_frozen() or layer.is_locked():
        raise ValueError("Слой ПП выключен, заморожен или заблокирован. Уточните состояние исходного слоя и подготовьте новый план")
    category_layer = doc.layers.get(CATEGORY_LAYER)
    if category_layer.is_off() or category_layer.is_frozen() or category_layer.is_locked():
        raise ValueError("Слой категорий выключен, заморожен или заблокирован. Подготовьте слой экспертиза категории")
    model = doc.modelspace()
    legend = {r["key"]: r for r in plan["legend"]}
    receipt = []
    for item in plan["items"]:
        kind = item["kind"]
        entities = []
        if item.get("existing_handle"):
            entity = doc.entitydb.get(item["existing_handle"].upper())
            expected_layer = CATEGORY_LAYER if kind == "category" else LAYER
            if entity is None or entity.dxf.layer != expected_layer:
                raise ValueError(f"{item['id']}: существующий объект не найден в требуемом слое {expected_layer}")
            if kind == "category":
                fmt = profile["category"]
                if (entity.dxftype() != "TEXT" or entity.dxf.text != category_label(item["category"], item["room_name"])
                    or math.dist(point(tuple(entity.dxf.insert)),point(item["position"])) > 2):
                    raise ValueError(f"{item['id']}: существующая категория отличается от плана")
                checks = {"height":fmt["height"], "width":fmt["width_factor"], "oblique":fmt["oblique_angle"],
                          "rotation":fmt.get("rotation",0), "color":fmt["color_index"]}
                style = doc.styles.get(entity.dxf.style)
                if any(not equivalent(entity.dxf.get_default(k),v) for k,v in checks.items()) or style.dxf.font.casefold()!=fmt["font_file"].casefold():
                    raise ValueError(f"{item['id']}: оформление существующей категории отличается от профиля")
            elif kind == "barrier":
                if entity.dxftype() not in {"LWPOLYLINE", "LINE"}:
                    raise ValueError("Существующая преграда должна быть линией или полилинией")
                actual = [list(p[:2]) for p in entity.get_points()] if entity.dxftype()=="LWPOLYLINE" else [tuple(entity.dxf.start)[:2],tuple(entity.dxf.end)[:2]]
                expected = [point(p) for p in item["points"]]
                if (len(actual)!=len(expected) or any(math.dist(a,b)>2 for a,b in zip(actual,expected))
                    or entity.dxf.color!=legend[item["legend_key"]]["color_index"] or entity.dxf.lineweight!=50):
                    raise ValueError(f"{item['id']}: существующая преграда отличается от плана")
                if bool(item.get("closed",False)) != (entity.closed if entity.dxftype()=="LWPOLYLINE" else False):
                    raise ValueError(f"{item['id']}: замкнутость существующей преграды отличается от плана")
            else:
                raise ValueError("existing_handle поддерживается для преград и категорий")
            entities.append(entity)
        elif kind == "barrier":
            entity = model.add_lwpolyline([point(p) for p in item["points"]], close=item.get("closed", False),
                dxfattribs={"layer": LAYER, "color": legend[item["legend_key"]]["color_index"],
                            "lineweight": 50, "linetype": "Continuous", "ltscale": item.get("linetype_scale", 100)})
            entities.append(entity)
        elif kind == "category":
            fmt = profile["category"]
            style = text_style(doc, fmt, "Категории")
            entity = model.add_text(category_label(item["category"], item["room_name"]), dxfattribs={
                "insert": point(item["position"]), "layer": CATEGORY_LAYER, "color": fmt["color_index"],
                "style": style, "height": fmt["height"], "width": fmt["width_factor"],
                "oblique": fmt["oblique_angle"], "rotation": fmt.get("rotation", 0),
                "halign": 0, "valign": 0, "lineweight": 0, "ltscale": fmt.get("linetype_scale", 100)})
            entities.append(entity)
        elif kind == "callout":
            fmt = profile["callout"].get("door_variant") if item["element"] in {"door", "gate", "curtain"} else profile["callout"]
            style = text_style(doc, fmt, "Выноски")
            entities.append(add_mtext(model, item["text"], item["position"], style, fmt, item.get("color_index", 1)))
            targets = item.get("targets") if item.get("element") == "vent_chamber" else [item["target"]]
            for target in targets:
                entities.append(model.add_line(point(item["leader_start"]), point(target),
                    dxfattribs={"layer": LAYER, "color": 256, "linetype": "ByLayer", "lineweight": -1}))
        elif kind == "dimension":
            style = dimensions_style(doc, profile)
            p1, p2, base = point(item["p1"]), point(item["p2"]), point(item["base"])
            angle = math.degrees(math.atan2(p2[1] - p1[1], p2[0] - p1[0]))
            dim = model.add_linear_dim(base=base, p1=p1, p2=p2, angle=angle, dimstyle=style,
                dxfattribs={"layer": LAYER, "color": item.get("color_index", 1), "lineweight": 0,
                            "ltscale": profile["dimensions"]["linetype_scale"]})
            dim.render()
            for sub in doc.blocks.get(dim.dimension.dxf.geometry):
                sub.dxf.layer = LAYER
                sub.dxf.transparency = 16777216
            entities.append(dim.dimension)
        elif kind == "legend":
            entry = legend[item["legend_key"]]
            fmt = profile["legend_text"]
            style = text_style(doc, fmt, "Легенда")
            entities.append(add_mtext(model, entry["name"], item["position"], style, fmt, entry["color_index"]))
            entities.append(model.add_line(point(item["start"]), point(item["end"]),
                dxfattribs={"layer": LAYER, "color": entry["color_index"], "lineweight": 50}))
        else:
            raise ValueError(f"Неподдерживаемый элемент: {kind}")
        receipt.append({"id": item["id"], "kind": kind, "handles": [e.dxf.handle for e in entities],
                        "expected": [signature(e) for e in entities]})
    doc.saveas(destination)
    reread = ezdxf.readfile(destination)
    changes = protected_changes(before, reread)
    if changes["missing"] or changes["changed"]:
        raise ValueError(f"Проверка сохранности исходной геометрии не пройдена: {str(changes)[:500]}")
    errors = verify_entities(reread, receipt)
    errors += supporting_changes(supporting_before, reread)
    if errors:
        raise ValueError("; ".join(errors[:20]))
    return {"created": receipt, "source_entities": before, "source_supporting":supporting_before,
            "result_supporting":supporting_snapshot(reread), "model_count_before": len(before),
            "model_count_after": len(reread.modelspace()), "destination": str(destination)}


def verify_entities(doc, receipt):
    errors = []
    for record in receipt:
        for handle, expected in zip(record["handles"], record["expected"]):
            entity = doc.entitydb.get(handle)
            if entity is None or not entity.is_alive:
                errors.append(f"{record['id']}: отсутствует объект {handle}")
                continue
            actual = signature(entity)
            if not equivalent(actual,expected):
                errors.append(f"{record['id']}: изменены геометрия, подпись или свойства {handle}")
            expected_layer = CATEGORY_LAYER if record["kind"] == "category" else LAYER
            if entity.dxf.layer != expected_layer:
                errors.append(f"{record['id']}: неверный слой")
    return errors
